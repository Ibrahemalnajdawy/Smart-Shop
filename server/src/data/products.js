const slugify = (value) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function getProductImage(id) {
  const image = productImageUrls[id] || additionalCategoryImageUrls[id];
  if (!image) throw new Error(`Missing sample product image for "${id}".`);
  return image;
}

function makeCuratedImagesUnique(products) {
  const seenImages = new Set();
  return products.map((product) => {
    if (!seenImages.has(product.image)) {
      seenImages.add(product.image);
      return product;
    }
    const image = getProductImage(product._id);
    seenImages.add(image);
    return { ...product, image };
  });
}

function createAdditionalProducts() {
  const additions = [];
  for (const profile of catalogProfiles) {
    const categoryProducts = curatedProducts.filter((product) => product.category === profile.category);
    const needed = Math.max(0, 41 - categoryProducts.length);
    const typePrices = basePricesByType[profile.category];
    if (!typePrices || typePrices.length !== profile.types.length) {
      throw new Error(`Missing base prices for "${profile.category}".`);
    }
    for (let index = 0; index < needed; index += 1) {
      const typeIndex = Math.floor(index / profile.variants.length);
      const variant = profile.variants[index % profile.variants.length];
      const type = profile.types[typeIndex % profile.types.length];
      const name = `${variant} ${type}`;
      const basePrice = typePrices[typeIndex % profile.types.length];
      const price = Math.round((basePrice * (variantPriceMultipliers[variant] || 1)) / 5) * 5;
      const id = `${slugify(profile.category)}-${slugify(variant)}-${slugify(type)}`;
      additions.push({
        _id: id,
        name,
        brand: profile.brands[(typeIndex + index) % profile.brands.length],
        category: profile.category,
        price,
        rating: Number((4.1 + ((index * 7) % 8) / 10).toFixed(1)),
        reviewCount: 24 + ((index * 89) % 900),
        description: `${name} for ${profile.useCase}. This generated sample listing demonstrates product discovery and comparison.`,
        image: getProductImage(id),
        specifications: {
          "Product type": type,
          Collection: variant,
          "Catalog data": "Illustrative sample; verify before purchase",
        },
        reviewSummary: "Illustrative sample review data only; verified customer feedback is not connected to this listing.",
        reviewHighlights: ["Generated sample listing", "Details are illustrative"],
      });
    }
  }
  return additions;
}

